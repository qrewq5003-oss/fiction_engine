def get_peak_finale(source: str) -> str | None:
    """
    Вернуть блок с техникой пикового финала для голоса.
    source — идентификатор профиля (chekhov, abercrombie, и т.д.)
    """
    entry = PEAK_FINALES.get(source)
    if not entry:
        return None

    return (
        f"ТЕХНИКА ПИКОВОГО ФИНАЛА: {entry['technique']}\n\n"
        f"Принцип: {entry['principle']}\n\n"
        f"Пример:\n{entry['example']}\n\n"
        f"Разбор: {entry['breakdown']}"
    )


def get_all_sources() -> list[str]:
    return list(PEAK_FINALES.keys())
