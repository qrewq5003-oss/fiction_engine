def edit_scene(project_id: int, text: str, mode: str, model_value: str,
               custom_instruction: str = "") -> str:
    """
    Редактировать кусок текста по указанному режиму.
    Возвращает переработанный текст.
    """
    if mode not in MODE_PROMPTS and not custom_instruction:
        raise ValueError(f"Неизвестный режим: {mode}")

    # Базовая инструкция
    if custom_instruction:
        task = f"ЗАДАЧА: {custom_instruction}"
    else:
        task = MODE_PROMPTS[mode]

    # Добавить голосовой профиль если активен
    voice_block = ""
    active_voice = get_active_voice(project_id)
    if active_voice and active_voice.get("profile"):
        voice_block = f"\n\nАКТИВНЫЙ ГОЛОС СЕРИИ:\n{active_voice['profile'][:800]}\n"

    user_prompt = f"""{task}
{voice_block}
ТЕКСТ ДЛЯ ПРАВКИ:
{text}

Верни только переработанный текст."""

    keys = get_api_keys_dict()
    return call_model(
        model_value, SYS_EDITOR, user_prompt,
        anthropic_key=keys["anthropic"],
        nano_key=keys["nano"],
        openai_key=keys["openai"],
        gemini_key=keys["gemini"],
        deepseek_key=keys["deepseek"],
        max_tokens=4000
    )


