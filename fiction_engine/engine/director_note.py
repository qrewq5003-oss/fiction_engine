"""
Режиссёрская заметка — на чём оборвалась глава, для следующей, у которой
нет плана: что осталось незавершённым, в каком состоянии герой, что он знает.

Не пересказ событий (это L3).
Не режим (это выбор пользователя).
Не предписание следующей главы: её задаёт автор (с 27.10; раньше — «тон, темп»).
"""
from typing import Callable

# Модель видит только конец главы и не видит задачи следующей, а заметка идёт
# писателю рядом с задачей автора. Прежнее «как подходить: тон, темп» и образцы
# «следующая сцена — разрядка» предписывали главу, которой модель не знает, —
# тот же спор, что у кнопки без плана (#134). Теперь — на чём глава оборвалась
# (разбор формулировок 26.10)
PROMPT = """Ниже — конец главы и состояние героев. Напиши заметку к следующей главе: 2-3 коротких предложения о том, на чём эта глава оборвалась: что осталось незавершённым, в каком состоянии герой, что он уже знает и чего ещё нет.
Не пересказывай главу и не придумывай события и тон следующей: их задаёт автор.

Так:
"Он не ответил на письмо и делает вид, что не читал. Вера знает про ключ, он — нет."
"Разговор оборвался на вопросе о деньгах. Оба злы и молчат."

Не так:
"Произошло предательство, нужно показать последствия." — пересказ и указание
"Следующая сцена — погоня по крышам." — событие следующей главы
"Она понимает, что брат лгал." — вывод за героя, которого в тексте нет

КОНЕЦ ГЛАВЫ (последние 800 символов):
{chapter_tail}

ТЕКУЩЕЕ СОСТОЯНИЕ ПЕРСОНАЖЕЙ:
{global_state}

Заметка (2-3 предложения, только суть):"""


def generate_director_note(
    project_id: int,
    chapter_num: int,
    chapter_text: str,
    state: dict,
    api_call_fn: Callable[..., str],
) -> str | None:
    """
    Сгенерировать режиссёрскую заметку после сохранения главы.
    Сохраняет в БД и возвращает текст заметки.
    """
    try:
        # Заметка к следующей главе уже есть — план из планировщика или
        # запись автора: не перезаписывать (сохранение было безусловным)
        from engine.db import get_director_note
        if get_director_note(project_id, chapter_num + 1):
            return None
        tail = chapter_text[-800:].strip()
        # Герои конца главы, а не первые 400 знаков State: там были только
        # второстепенные, добавленные позже (разбор 21.10)
        from engine.pipeline_context import extract_relevant_state
        global_state = extract_relevant_state(state, tail, before_chapter=chapter_num + 1)[:1500]

        prompt = PROMPT.format(
            chapter_tail=tail,
            global_state=global_state,
        )

        note = api_call_fn(prompt)
        if not note or len(note.strip()) < 10:
            return None

        note = note.strip()

        from engine.db import save_director_note
        save_director_note(project_id, chapter_num, note, source="auto")

        return note

    except Exception as e:
        # Сбой — в журнал: раньше заметка пропадала без следа (разбор 21.10)
        from engine.error_policy import ErrorLevel, handle_error
        handle_error(f"director_note: заметка к гл.{chapter_num + 1}", e, level=ErrorLevel.RECOVERABLE)
        return None
