# ПОРОГ ПРИНЯТИЯ — решение владельца 22.09: ИТОГ ≥ 35, каждый критерий ≥ 4.
#
# Как сюда пришли, и в чём была моя ошибка.
#
# Сначала порог калибровался по РАЗДЕЛЕНИЮ: чтобы принимал целую главу и
# отвергал перемешанную. Это доказывает, что мера вообще что-то меряет, —
# и даёт унизительно низкую планку: «текст не разрезан на куски». Выходило
# 30, а медиана настоящих глав на этом судье — 29. «ПРИНЯТЬ» получало
# смысл «не хуже обычного».
#
# Живой прогон 22.09 это и показал: все пять критериев по 6, сумма ровно
# 30. По моему расчёту — принять; судья сказал «НА ДОРАБОТКУ» и рассудил
# лучше. Шестёрки по всем критериям — середина, а принимать середину
# незачем.
#
# Замер на Haiku, 15 настоящих глав:
#
#     порог 30   проходят  7 из 15   «не хуже обычного»
#     порог 32   проходят  2 из 15
#     порог 35   проходит  1 из 15   ← выбрано: заметно выше середины
#     порог 40   проходит  0 из 15   прежний, недостижимый
#
# Планка редко берётся — и это правдивое сообщение о том, где сейчас
# движок, а не порок планки. Прежний порог 40 был плох не высотой, а тем,
# что при отказе никто не знал, чего не хватает: оценки по критериям не
# разбирались. Теперь «30 из 50, все шестёрки» — внятный диагноз.
#
# Планка отдельного критерия остаётся 4: её задача — не пускать главу с
# одним начисто провалённым свойством, а не требовать ровного отличия.
ACCEPT_TOTAL         = 35    # из 50
ACCEPT_MIN_CRITERION = 4     # из 10, по каждому из пяти

# Свой порог у судьи (калибровка 16–17.10, bench/judges-2026-10-17.json).
# Шкала у каждого своя: Sol ставит живым главам 19–38 (медиана 31,5), Sonnet
# — 25–39 (медиана 30). Порог — чуть выше медианы живых глав («лучше
# обычного», как у Haiku) и выше испорченных копий (перемешанные абзацы,
# обратный порядок, дубль куска). Замер — с судьёй, не видящим балл критика
# (critique_for_judge). При 35 Sol принимал 2 главы из 12.
#     Sol    порог 32: живые 5 из 12, испорченные 0 из 12
#     Sonnet порог 33: живые 5 из 12, испорченные 1 из 12 — дубль куска,
#                      его ловит арифметика (detect_truncation и повторы)
JUDGE_ACCEPT_TOTAL: dict[str, int] = {
    # 18.10: 32 → 30 с критиком Haiku 5.5 вместо Kimi (bench/critic-no-nano-2026-10-18.json):
    # при 30 на 48 главах проходят 12/24 живых и 0/24 испорченных, при 32 — 8/24
    "gpt-6.1-sol": 30,
    "claude-sonnet-5": 33,
}

# Судьи, которым разбор критика не передаётся: оценивают главу сами.
# Sonnet без разбора отличает живые главы от испорченных лучше, чем с ним:
# 12/12 и 11/12 на двух выборках; с разбором Kimi 12/12, с разбором Luna —
# 10/12 и строже (bench/critic-no-nano-2026-10-18.json). Sol, наоборот, без
# разбора хуже: 9/12 против 11–12/12 — ему разбор идёт.
JUDGE_WITHOUT_CRITIQUE = ("claude-sonnet-5",)


def judge_sees_critique(model_judge: str = "") -> bool:
    m = (model_judge or "").split("::")[-1]
    return not any(k in m for k in JUDGE_WITHOUT_CRITIQUE)


def accept_total_for(model_judge: str = "") -> int:
    """Порог ИТОГА для этого судьи; не калиброван — ACCEPT_TOTAL."""
    m = (model_judge or "").split("::")[-1]
    return next((v for k, v in JUDGE_ACCEPT_TOTAL.items() if k in m), ACCEPT_TOTAL)


# Модули ремесла писателю (решение владельца 17.10, bench/judges-2026-10-17.json).
# GPT-6.1 Sol: без модулей не хуже (Sonnet-судья 3:2 устойчивых, nano 7.74 против
# 7.75), промпт 17 тыс. символов вместо 44. Sonnet: модули оставлены — без них
# сравнений «словно/будто» на ~20% больше (1.85 против 1.47 на 1000 слов),
# пары Sol 5:7 в пределах шума.
CRAFT_MODULES_OFF = ("gpt-6.1-sol",)


def craft_modules_on(model_value: str = "") -> bool:
    m = (model_value or "").split("::")[-1]
    return not any(k in m for k in CRAFT_MODULES_OFF)

@dataclass
class StepConfig:
    """
    Конфигурация одного шага pipeline.

    name       — идентификатор: "generate" | "edit" | "critique" | "judge"
    enabled    — False = шаг пропускается без ошибки
    max_tokens — лимит ответа для этого шага
    model_role — какую модель использовать (gen / critic / editor / judge)
                 None = берётся автоматически по имени шага
    """
    name:       str
    enabled:    bool  = True
    max_tokens: int   = 6000
    model_role: str | None = None   # явный override модели

    def __post_init__(self) -> None:
        valid = {"generate", "edit", "critique", "judge"}
        if self.name not in valid:
            raise ValueError(f"Неизвестный шаг: '{self.name}'. Допустимые: {valid}")

    @property
    def default_model_role(self) -> str:
        """Роль модели по умолчанию если model_role не задан явно."""
        return self.model_role or {
            "generate": "gen",
            "edit":     "editor",
            "critique": "critic",
            "judge":    "judge",
        }[self.name]

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "StepConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})


