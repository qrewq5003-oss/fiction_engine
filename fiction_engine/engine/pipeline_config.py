# ПОРОГ ПРИНЯТИЯ — решение владельца 22.09: ИТОГ ≥ 35, каждый критерий ≥ 4.
#
# Как сюда пришли, и в чём была моя ошибка.
#
# Сначала порог калибровался по РАЗДЕЛЕНИЮ: чтобы принимал целую главу и
# отвергал перемешанную. Это доказывает, что мера вообще что-то меряет, —
# и даёт унизительно низкую планку: «текст не разрезан на куски». Выходило
# 30, а медиана настоящих глав на этом судье — 29. «ПРИНЯТЬ» получало
# смысл «не хуже обычного».
#
# Живой прогон 22.09 это и показал: все пять критериев по 6, сумма ровно
# 30. По моему расчёту — принять; судья сказал «НА ДОРАБОТКУ» и рассудил
# лучше. Шестёрки по всем критериям — середина, а принимать середину
# незачем.
#
# Замер на Haiku, 15 настоящих глав:
#
#     порог 30   проходят  7 из 15   «не хуже обычного»
#     порог 32   проходят  2 из 15
#     порог 35   проходит  1 из 15   ← выбрано: заметно выше середины
#     порог 40   проходит  0 из 15   прежний, недостижимый
#
# Планка редко берётся — и это правдивое сообщение о том, где сейчас
# движок, а не порок планки. Прежний порог 40 был плох не высотой, а тем,
# что при отказе никто не знал, чего не хватает: оценки по критериям не
# разбирались. Теперь «30 из 50, все шестёрки» — внятный диагноз.
#
# Планка отдельного критерия остаётся 4: её задача — не пускать главу с
# одним начисто провалённым свойством, а не требовать ровного отличия.
ACCEPT_TOTAL         = 35    # из 50
ACCEPT_MIN_CRITERION = 4     # из 10, по каждому из пяти

@dataclass
class StepConfig:
    """
    Конфигурация одного шага pipeline.

    name       — идентификатор: "generate" | "edit" | "critique" | "judge"
    enabled    — False = шаг пропускается без ошибки
    max_tokens — лимит ответа для этого шага
    model_role — какую модель использовать (gen / critic / editor / judge)
                 None = берётся автоматически по имени шага
    """
    name:       str
    enabled:    bool  = True
    max_tokens: int   = 6000
    model_role: str | None = None   # явный override модели

    def __post_init__(self) -> None:
        valid = {"generate", "edit", "critique", "judge"}
        if self.name not in valid:
            raise ValueError(f"Неизвестный шаг: '{self.name}'. Допустимые: {valid}")

    @property
    def default_model_role(self) -> str:
        """Роль модели по умолчанию если model_role не задан явно."""
        return self.model_role or {
            "generate": "gen",
            "edit":     "editor",
            "critique": "critic",
            "judge":    "judge",
        }[self.name]

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict) -> "StepConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})


# ─── PipelineConfig ───────────────────────────────────────────────────────────

@dataclass
class PipelineConfig:
    """
    Полная декларативная конфигурация pipeline.

    steps               — список шагов в порядке выполнения
    max_iterations      — максимум кругов generate→critique→judge
    score_threshold     — принять автоматически если judge даёт >= X/50
    accept_on_timeout   — принять последний вариант если кончились итерации
    max_auto_retries    — сколько раз автоматически повторить edit→critique→judge
                          при вердикте «НА ДОРАБОТКУ» (0 = opt-in, выкл. по умолчанию)
    description         — человекочитаемое описание пресета
    """
    steps:              list[StepConfig]
    max_iterations:     int   = 3
    # Планка авто-принятия. По умолчанию — общий порог принятия:
    # своя копия здесь расходилась дважды (стояло 38, когда порог был
    # 40; стояло 30, когда порог стал 35).
    score_threshold:    float = ACCEPT_TOTAL
    accept_on_timeout:  bool  = True    # принять лучший вариант по истечении итераций
    max_auto_retries:   int   = 0       # авто-цикл: 0 = отключён (opt-in)
    description:        str   = ""

    @property
    def enabled_steps(self) -> list[StepConfig]:
        return [s for s in self.steps if s.enabled]

    @property
    def step_names(self) -> list[str]:
        return [s.name for s in self.enabled_steps]

    def has_step(self, name: str) -> bool:
        return any(s.name == name and s.enabled for s in self.steps)

    def get_step(self, name: str) -> StepConfig | None:
        return next((s for s in self.steps if s.name == name), None)

    def with_step_disabled(self, name: str) -> "PipelineConfig":
        """Вернуть новый конфиг с отключённым шагом (иммутабельно)."""
        new_steps = [
            StepConfig(s.name, enabled=False if s.name == name else s.enabled,
                       max_tokens=s.max_tokens, model_role=s.model_role)
            for s in self.steps
        ]
        import dataclasses
        return dataclasses.replace(self, steps=new_steps)

    def to_dict(self) -> dict:
        return {
            "steps":             [s.to_dict() for s in self.steps],
            "max_iterations":    self.max_iterations,
            "score_threshold":   self.score_threshold,
            "accept_on_timeout": self.accept_on_timeout,
            "max_auto_retries":  self.max_auto_retries,
            "description":       self.description,
        }

    @classmethod
    def from_dict(cls, d: dict) -> "PipelineConfig":
        steps = [StepConfig.from_dict(s) for s in d.get("steps", [])]
        return cls(
            steps=steps,
            max_iterations=d.get("max_iterations", 3),
            score_threshold=d.get("score_threshold", ACCEPT_TOTAL),
            accept_on_timeout=d.get("accept_on_timeout", True),
            max_auto_retries=d.get("max_auto_retries", 0),
            description=d.get("description", ""),
        )

    def to_pipeline_steps(self) -> list:
        """
        Конвертировать в список PipelineStep для _execute_steps().
        Совместимость с pipeline.py.
        """
        from .pipeline import PipelineStep
        return [PipelineStep(s.name, s.enabled,
                            s.max_tokens or step_token_budget(s.name))
                for s in self.steps]


# ─── Бюджет вывода под объём главы ────────────────────────────────────────────
#
# Промпты (state_prompts.py) требуют «СТРОГО 2500-3000 слов».
# Русский текст дорог в токенах: на реальной главе проекта — 6.8 символа на
# слово, а кириллица укладывается примерно в 2.0-2.5 символа на токен.
#
#   3000 слов × 6.8 симв. = 20 400 симв. → 8 200 … 10 200 токенов
#   2500 слов × 6.8 симв. = 17 000 симв. → 6 800 …  8 500 токенов
#
# Прежние значения (generate=8000, edit=7000) лежали НИЖЕ этого диапазона:
# модель упиралась в потолок и глава обрывалась на середине фразы. Причём
# edit был меньше generate — то есть редактура резала главу, которую
# генерация успела написать целиком.
#
# max_tokens — это потолок, а не предоплата: счёт идёт за реально выданные
# токены, поэтому запас ничего не стоит.

# Нижняя граница требования к объёму. Вместе с TARGET_CHAPTER_WORDS даёт
# «2500-3000 слов» — фразу, которая была вписана в промпты девятью копиями,
# пока константы жили отдельно. Значения совпадали, но сходство держалось
# на внимательности: у TARGET_CHAPTER_WORDS так и стоял комментарий «верх
# требования ИЗ ПРОМПТОВ», то есть зависимость была признана и оставлена
# ручной. Ровно так разошлись числа абзацев (15-20 против 25-35) и норма
# ритма, которую знал только критик.
MIN_CHAPTER_WORDS = 2500

TARGET_CHAPTER_WORDS = 3000          # верх требования; в промпты идёт отсюда
RU_CHARS_PER_WORD    = 6.8           # замер на реальных главах проекта
RU_CHARS_PER_TOKEN   = 2.0           # консервативная оценка для кириллицы
PROSE_HEADROOM       = 1.15          # заголовок, разбивка, хвост фразы


def tokens_for_words(words: int = TARGET_CHAPTER_WORDS) -> int:
    """Сколько токенов вывода нужно, чтобы уместить главу заданного объёма."""
    chars = words * RU_CHARS_PER_WORD
    return int(chars / RU_CHARS_PER_TOKEN * PROSE_HEADROOM)


# Единый потолок для шагов, которые выдают полный текст главы.
# generate и edit обязаны быть равны: иначе редактура обрежет генерацию.
PROSE_MAX_TOKENS = tokens_for_words()          # ≈ 11 700

# Минимальный приемлемый объём — ниже него глава считается недописанной.
MIN_ACCEPTABLE_WORDS = 2000


def scene_word_budget(weights: tuple[int, ...]) -> list[int]:
    """
    Слова по сценам — так, чтобы сумма давала требуемый объём.

    Разбивка по сценам НЕ СХОДИЛАСЬ с требованием. В промптах стояло:

        master:   900 + 700 + 700 = 2300
        quality:  1000 + 1000     = 2000

    при требовании «СТРОГО 2500-3000 слов». Модель следует конкретным
    числам по сценам, а не общему требованию — и выдаёт ровно то, что ей
    расписали. Живой прогон 22.09: 1660 слов при расписанных 2300.

    Считаем от ВЕРХА диапазона, а не от середины: модели систематически
    недобирают, и запас сверху ближе к цели, чем недобор снизу.

    weights — пропорции сцен, сохранённые из прежней разбивки:
    9:7:7 для трёх сцен (первая длиннее), 1:1 для двух.
    """
    total = sum(weights)
    out = [round(TARGET_CHAPTER_WORDS * w / total / 50) * 50 for w in weights]
    # Округление вниз не должно уронить сумму ниже нижней границы.
    while sum(out) < MIN_CHAPTER_WORDS:
        out[0] += 50
    return out


def volume_rule_for_prompt(with_paragraphs: bool = True) -> str:
    """
    Требование к объёму — из тех же чисел, по которым его потом проверяют.

    detect_truncation ругается ниже MIN_ACCEPTABLE_WORDS, промпт требует
    MIN_CHAPTER_WORDS–TARGET_CHAPTER_WORDS. Раньше эти числа стояли в
    промптах девятью литералами.
    """
    tail = " (25-35 абзацев)" if with_paragraphs else ""
    return (f"СТРОГО {MIN_CHAPTER_WORDS}-{TARGET_CHAPTER_WORDS} слов{tail}")


def volume_check_for_prompt() -> str:
    """Самопроверка объёма — та же нижняя граница."""
    return (f"Прежде чем закончить — проверь себя: написано ли уже "
            f"{MIN_CHAPTER_WORDS} слов? Если меньше, глава не дописана: "
            f"продолжай сцену, не сворачивай к финалу.")


