def get_preset(name: str) -> PipelineConfig:
    """
    Получить пресет по имени. Бросает ValueError для неизвестного имени.
    Используется в web/CLI для передачи конфига как строки.
    """
    if name not in PRESETS:
        raise ValueError(
            f"Неизвестный пресет '{name}'. Доступные: {list(PRESETS)}"
        )
    return PRESETS[name]


def list_presets() -> list[dict]:
    """Список всех пресетов для UI."""
    return [
        {
            "id":          name,
            "description": cfg.description,
            "steps":       cfg.step_names,
            "max_iter":    cfg.max_iterations,
        }
        for name, cfg in PRESETS.items()
    ]


# ─── Судья и генератор из одного семейства ───────────────────────────────────
#
# Замер 13.10 (bench/ab-writers-sonnet-2026-10-13.json, tools/self_recognition.py):
# «одну из двух глав написал ты — какую?» — Sonnet 5.5 узнал свою главу 16
# раз из 16, Opus 5.5 главу Sonnet — тоже 16 из 16, и Sonnet-судья голосовал
# за свою главу во всех парах; DeepSeek и Kimi свои главы не узнали (6 из 16).
# Поэтому предупреждаем, когда Claude судит Claude, и когда судит та же
# модель, что писала: генератор не должен судить себя.

def scorer_model_for(writer: str) -> str:
    """
    Оценщик главы писателя writer: «scorer_model» из настроек, если он другой
    семьи; иначе проверяющий другой семьи (plan_check.plan_checker_model); нет
    такого — «» (оценки нет). Писатель неизвестен — настройка как есть.

    Раньше без настройки оценщиком становился сам писатель (Sonnet оценивал
    Sonnet), а настройка той же семьи бралась как есть (разбор 21.10).
    """
    from .db_settings import get_setting
    m = (get_setting("scorer_model") or "").strip()
    if not writer or (m and model_family(m) != model_family(writer)):
        return m
    from .plan_check import plan_checker_model
    return plan_checker_model(writer)[0]


def model_family(model_value: str) -> str:
    """Семейство модели по её значению «провайдер::модель»: claude, deepseek, kimi…"""
    provider, _, model = (model_value or "").partition("::")
    m = (model or provider).lower()
    if provider in ("anthropic_direct", "claude_subscription") or "claude" in m:
        return "claude"
    for fam, keys in (("deepseek", ("deepseek",)), ("kimi", ("kimi", "moonshot")),
                      ("glm", ("glm", "z-ai", "zhipu")), ("gpt", ("gpt", "openai/")),
                      ("gemini", ("gemini",)), ("qwen", ("qwen",)), ("mistral", ("mistral",)),
                      ("mimo", ("mimo", "xiaomi"))):
        if any(k in m for k in keys):
            return fam
    return m


def judge_bias_warning(model_gen: str, model_judge: str) -> str:
    """Предупреждение автору, если судья пристрастен к тексту генератора; иначе «»."""
    if not model_gen or not model_judge:
        return ""
    # Любая семья, не только Claude: GPT не судит GPT (Sol и Luna — одна семья).
    # Новый запуск с таким судьёй не стартует (pipeline.start_pipeline); здесь —
    # для запусков, начатых раньше. Kimi и DeepSeek больше не советуем: модели
    # nano убраны (18.10)
    if model_family(model_gen) == model_family(model_judge):
        return (f"Судья и писатель — одной семьи ({model_family(model_gen)}): модель узнаёт свой текст "
                "и голосует за него (Claude — 16 раз из 16). Оценка судьи, скорее всего, завышена — "
                "поставьте судьёй модель другой семьи (набор ролей).")
    return ""
