"""
judge_rubric.py — правила оценки v2: определения критериев, шкала и строки-шлагбаумы.

Замер 20.10 по «Фону» (57 оценок судьи Sol, 57 разборов критика Haiku) и
14 калибровкам «живые против испорченных»:

- судья не видел определений: ему сказано «по тем же 5 критериям», а сами
  критерии описаны только у критика;
- судья ставил почти одну оценку на критерий: голос 7 в 51 главе из 57,
  персонажи — в 41, диалог — в 39; итог решала структура (23 % разброса
  суммы, связь с итогом 0.85);
- «структура» была баллом за хронологию и логику: «хронологические
  несостыковки снижают оценку структуры», «ошибки доказательной логики учтены
  в оценках структуры и сцен»; в замечаниях даты — 45 из 57, финал и темп — 21;
- одна ошибка снималась в двух-трёх местах: экспозиция — в структуре, сценах
  и диалоге; даты — в структуре, сценах и персонажах.

v2: у каждого критерия определение, недостаток считается в одном месте,
шкала подписана. Связность (кто что сделал и знает, факты серии) — строка
вне балла, у детектива ещё логика выводов. Балл по-прежнему из 50, пороги
судей те же, что у v1 (калибровка 20.10, tools/calib_judge.py CALIB_RUBRIC=v2).

«ГРУБО» отправляет главу на доработку, и редактор получает эти строки первыми
(gate_task). Переоценка «Фона» 20.10 по первым определениям: «ГРУБО» у 9 из 12
принятых глав, почти всегда за даты и минуты («воскресенье» при пн 16.11, 21:52
при рейсе 21:50), и судья брал факты из разбора критика, а не из главы. Поэтому
даты и время — не выше «ЕСТЬ», а «ГРУБО» — только с цитатой из главы. С этими
определениями — 6 из 12, все по существу: догадка или слух подаются фактом,
героиня «впервые узнаёт» то, что вчера писала сама. Без шлагбаума такие ошибки
в принятой главе не правит никто: в первом круге редактора нет.
"""

from __future__ import annotations

import re

RUBRIC_KEY = "judge_rubric"
RUBRICS = ("v1", "v2")

GATE_LEVELS = ("ОК", "ЕСТЬ", "ГРУБО")
GATE_FAIL = "ГРУБО"
COHERENCE = "СВЯЗНОСТЬ"
LOGIC = "ЛОГИКА ВЫВОДОВ"


# Правила запуска: шаги круга судят по правилам, с которыми запуск начат,
# а не по нынешней настройке (pipeline.run_pipeline_step, разбор 21.10)
from contextvars import ContextVar
RUN_RUBRIC: ContextVar[str] = ContextVar("fe_run_rubric", default="")


def rubric() -> str:
    """
    Правила оценки из настроек: v1 (прежние) или v2. По умолчанию v2 (21.10):
    «Ночная смена» — 4 главы через приложение, «ГРУБО» по существу, редактор
    исправлял за круг, ложные «ГРУБО» критика судья снижал до «ЕСТЬ». Порог
    судьи тот же: испорченные главы останавливает «ГРУБО» (0 из 8 при любом
    пороге), живые при нынешних порогах проходят.
    """
    if RUN_RUBRIC.get() in RUBRICS:
        return RUN_RUBRIC.get()
    try:
        from .db_settings import get_setting
        r = (get_setting(RUBRIC_KEY) or "").strip()
    except Exception:          # нет базы — по умолчанию
        r = ""
    return r if r in RUBRICS else "v2"


CRITERIA = """КРИТЕРИИ (каждый 0–10). Каждый недостаток снижай в одном критерии — там, где он живёт; дважды за одно не снижай.
1. ГОЛОС — манера рассказчика: своя интонация, точное слово. Снижают: штампы и ИИ-обороты, эмоция, названная словом вместо тела, один и тот же приём раз за разом.
2. СТРУКТУРА — форма главы: чем начинается и цепляет, как нарастает, есть ли поворот, тянет ли финал дальше, сдвинулось ли состояние героя, отношений или расследования. Снижают: провисания, топтание на месте, финал без сдвига. Хронологию, даты, факты серии и доказательность выводов здесь НЕ оценивай — для них отдельная строка.
3. ПЕРСОНАЖИ — мотивы и последовательность: поступок вытекает из того, кто человек и что он знает; у второстепенных своя цель, а не роль подсказки; позиция меняется с поводом.
4. СЦЕНЫ — присутствие: сцена разыграна, а не пересказана; пространство, детали, физика. Снижают: авторский пересказ событий и улик, удобные совпадения, которые двигают сюжет за героя.
5. ДИАЛОГ — естественность и подтекст; кто говорит, понятно без ремарок. Снижают: монолог-справка и лекция в речи (только здесь, не в сценах и не в структуре).

ШКАЛА каждого критерия: 8 — сильно, недостатки единичны и мелкие; 6 — крепко, но недостатки заметны; 4 — недостаток мешает читать главу; 2 — критерий провален. Промежуточные баллы ставь тоже. Одинаковый балл всем критериям — только если они правда равны."""

_GATES = {COHERENCE: "кто что сделал, видел и знает; порядок событий; факты серии и прошлых глав. "
                     "Даты, дни недели и время суток — не выше ЕСТЬ."}

# Логика выводов — свойство жанра, а не любой книги: строка только там, где
# сюжет держится на выводах из улик. «Фон» (19.10): «один жетон не доказывает
# регулярных поездок», «пересказ объявляется фактом» — четвёртая по частоте
# тема замечаний судьи
_GENRE_GATES = {
    "detective": {LOGIC: "следует ли вывод героя из улик, которые видит читатель; догадка не подаётся "
                         "как доказанный факт."},
}


def _genre_key(genre: str) -> str:
    from .unified_engine import detect_genre
    raw = (genre or "").lower()
    return (detect_genre(raw) or raw).split("_")[0]


def gates(genre: str = "") -> dict[str, str]:
    """Строки вне балла → что в них: связность всегда, логика выводов — по жанру."""
    return {**_GATES, **(_GENRE_GATES.get(_genre_key(genre), {}) if genre else {})}


def gate_names(genre: str = "") -> list[str]:
    return list(gates(genre))


def gates_block(genre: str = "", judge: bool = False) -> str:
    """Что значат строки вне балла — перед форматом ответа. judge — судье: он видит разбор критика."""
    lines = [("СТРОКИ ВНЕ БАЛЛА (ОК — ошибок нет; ЕСТЬ — мелкие, читатель споткнётся, но поймёт; "
              "ГРУБО — ошибка меняет, кто что сделал, видел или знает, или ломает вывод, на котором "
              "держится сюжет):")]
    lines += [f"- {n} — {d}" for n, d in gates(genre).items()]
    lines.append("ГРУБО — только с цитатой из текста главы. Расхождение дат, дней недели, часов и минут — "
                 "ЕСТЬ, а не ГРУБО: его правит редактор.")
    if judge:
        lines.append("Ошибку, которую ты знаешь только из разбора критика, а в тексте главы не видишь, "
                     "не ставь выше ЕСТЬ.")
    return "\n".join(lines)


def gate_format(genre: str = "") -> str:
    """Строки вне балла в формате ответа."""
    return "\n".join(f"{n}: [ОК / ЕСТЬ / ГРУБО] — [ошибки кратко, с цитатой из главы; нет — «нет»]"
                     for n in gate_names(genre))


def verdict_rule(total: int, min_criterion: int, genre: str = "") -> str:
    names = " и ".join(gate_names(genre))
    return (f"ПРАВИЛО ВЕРДИКТА: ПРИНЯТЬ, если ИТОГ ≥ {total}, каждый из 5 критериев ≥ {min_criterion} "
            f"и {names} — не ГРУБО. Иначе — НА ДОРАБОТКУ.")


def sys_judge(total: int, min_criterion: int, genre: str = "") -> str:
    # Судья видит один текст главы (с 23.10, #162 — без текста прошлого круга):
    # «сравниваешь два варианта» и «УЛУЧШЕНИЯ после редактуры» остались от прежнего
    # судьи; строку УЛУЧШЕНИЯ код не читал, а в первом круге редактуры нет вовсе
    lines = gate_format(genre)
    return f"""Ты — главный редактор серии. Оцениваешь главу и выносишь вердикт.

{CRITERIA}

{gates_block(genre, judge=True)}

Формат ответа — строго:
ГОЛОС: [0-10] — [одна фраза: за что балл]
СТРУКТУРА: [0-10] — [одна фраза]
ПЕРСОНАЖИ: [0-10] — [одна фраза]
СЦЕНЫ: [0-10] — [одна фраза]
ДИАЛОГ: [0-10] — [одна фраза]
ИТОГ: [0-50]
{lines}
ОСТАТОК: [что ещё можно улучшить]
ВЕРДИКТ: [ПРИНЯТЬ / НА ДОРАБОТКУ]
{verdict_rule(total, min_criterion, genre)}
ОБОСНОВАНИЕ: [1-2 предложения с конкретными числами — почему ПРИНЯТЬ или НА ДОРАБОТКУ]"""


def critic_criteria(genre: str = "") -> tuple[str, str]:
    """→ (критерии, шкала и строки вне балла; строки для формата) — критику v2: тот же язык, что у судьи."""
    return f"{CRITERIA}\n\n{gates_block(genre)}", gate_format(genre)


_GATE = re.compile(r"(" + "|".join(map(re.escape, (COHERENCE, LOGIC))) + r")\s*[:—–-]\s*\[?\s*(ОК|OK|ЕСТЬ|ГРУБО)",
                   re.IGNORECASE)


def parse_gates(text: str) -> dict[str, str]:
    """{СВЯЗНОСТЬ: ОК|ЕСТЬ|ГРУБО, …} из ответа; строки нет — её нет и в словаре."""
    from .pipeline_llm import _plain
    out: dict[str, str] = {}
    for name, level in _GATE.findall(_plain(text or "")):
        level = level.upper().replace("OK", "ОК")
        out.setdefault(name.upper(), level)
    return out


def failed_gates(gates: dict[str, str]) -> list[str]:
    return [k for k, v in gates.items() if v == GATE_FAIL]


def rough_lines(*texts: str) -> list[str]:
    """Строки «ГРУБО» из разбора критика и ответа судьи, без повторов."""
    from .pipeline_llm import _plain
    out: list[str] = []
    for text in texts:
        for line in _plain(text or "").splitlines():
            m = _GATE.search(line)
            line = line.strip(" -*")
            if m and m.group(2).upper() == GATE_FAIL and line not in out:
                out.append(line)
    return out


def gate_task(lines: list[str]) -> str:
    """Задание редактору по строкам «ГРУБО» → текст перед разбором (как point_edit.plan_task)."""
    from .point_edit import PLAN_MARK
    return ("СНАЧАЛА — СВЯЗНОСТЬ. Разбор нашёл ошибки, которые меняют ход событий:\n"
            + "\n".join(f"- {x[:600]}" for x in lines)
            + "\nИсправь эти места правкой: приведи их в согласие с остальной главой и прошлыми главами, "
            "сюжет не меняй. Ошибки, которой в тексте нет, не выдумывай — пропусти пункт. Это важнее "
            f"остального. У таких правок \"why\" начинай с «{PLAN_MARK}».")
