"""Сигналы текста: эхо подготовки — присказки из карточек и правила голоса в главе."""


def test_catchphrase_from_card_over_norm():
    """«Фон», 19.10: присказка из карточки шла 3–5 раз за главу; одна-две — норма."""
    from engine.text_signals import catchphrases, prep_echo_signals
    cards = ("## Варя\nРечь: быстрая, ироничная, «окей, смотрим»\nВнешность: «горчичное пальто»\n"
             "## Белова\nОсобенности речи: «юридически говоря», точно называет статьи")
    assert catchphrases(cards) == ["окей, смотрим", "юридически говоря"]      # только строки речи
    two = "Окей, смотрим. Кадр. " * 2 + "Горчичное пальто. " * 5
    assert prep_echo_signals(two, cards) == []
    four = "— Юридически говоря, это кража. " * 2 + "— Юридически, говоря честно, да. И юридически говоря — нет."
    sig = prep_echo_signals(four, cards)
    assert len(sig) == 1 and "«юридически говоря» — 4 раз" in sig[0]


def test_voice_rule_echo():
    """Правило голоса стало текстом главы; эталон из книги — не правило, его слова не считаются."""
    from engine.text_signals import prep_echo_signals
    voice = ("Первое лицо. Чувства — через действие и экран.\nКак Варя думает: сначала факт, потом вывод.\n\n"
             "ЭТАЛОН (из книги)\n— Видишь? Каждый кадр новый.")
    assert prep_echo_signals("— Видишь? Каждый кадр новый, — сказала я.", "", voice) == []
    sig = prep_echo_signals("Я всегда так: сначала факт, потом вывод. Так учил отец.", "", voice)
    assert sig and "«сначала факт потом вывод" in sig[0]
